#!/usr/bin/env python3
"""Generate src/catalog/MockCatalog.cpp from a snapshot of the OSC /contents API.

Usage: curl -A OpenShop-dev https://hbb1.oscwii.org/api/v4/contents > contents.json
       python3 -I tools/gen_mock_catalog.py contents.json > src/catalog/MockCatalog.cpp
"""
import json, sys

PER_CATEGORY = 12
MAX_LONG = 2500

_NAMED = {"\\": "\\\\", '"': '\\"', "\n": "\\n", "\r": "\\r", "\t": "\\t"}

def lit(s):
    """C++ string literal. Control characters become 3-digit octal escapes (never hex: C++ hex
    escapes swallow following hex digits), and "??" is split so it can't form a trigraph."""
    out = []
    for ch in s:
        if ch in _NAMED:
            out.append(_NAMED[ch])
        elif ord(ch) < 0x20 or ord(ch) == 0x7f:
            out.append("\\%03o" % ord(ch))
        else:
            out.append(ch)
    return '"' + "".join(out).replace("??", "?\\?") + '"'

def strs(xs):
    return "{" + ", ".join(lit(x) for x in xs) + "}"

with open(sys.argv[1], encoding="utf-8") as f:
    apps = json.load(f)
picked = []
for cat in ["games", "emulators", "utilities", "media", "demos"]:
    inCat = sorted((a for a in apps if a["category"] == cat), key=lambda a: -a["downloads"])
    picked += inCat[:PER_CATEGORY]

CATEGORIES = [("games", "Games", "Game", "Games"), ("emulators", "Emulators", "Emulator", "Emulators"),
              ("utilities", "Utilities", "Utility", "Utilities"), ("media", "Media", "Media", "Media"),
              ("demos", "Demos", "Demo", "Demos")]
PACKAGE = {"dol": "PackageType::Dol", "elf": "PackageType::Elf"}

def asset(a, kind, key, default):
    return (a["assets"].get(kind) or {}).get(key, default)

out = ['// Generated by tools/gen_mock_catalog.py. Do not edit by hand.',
       '// App metadata (c) its respective authors, via the Open Shop Channel repository.',
       '#include "catalog/Catalog.h"', '',
       'void loadMockCatalog(Catalog& c) {',
       '\tc.categories = {']
for name, display, singular, plural in CATEGORIES:
    out.append('\t\t{.name = %s, .display = %s, .singular = %s, .plural = %s},' %
               (lit(name), lit(display), lit(singular), lit(plural)))
out += ['\t};', '\tc.apps = {']
for a in picked:
    longd = a["description"]["long"] or a["description"]["short"]
    if len(longd) > MAX_LONG:
        longd = longd[:MAX_LONG].rsplit(" ", 1)[0] + "…"
    fields = [
        ("slug", lit(a["slug"])), ("name", lit(a["name"])), ("author", lit(a["author"])),
        ("category", lit(a["category"])), ("shortDesc", lit(a["description"]["short"])),
        ("longDesc", lit(longd)), ("version", lit(a["version"])),
        ("authors", strs(a.get("authors", []))), ("contributors", strs(a.get("contributors", []))),
        ("iconUrl", lit(asset(a, "icon", "url", ""))),
        ("archiveUrl", lit(asset(a, "archive", "url", ""))), ("archiveMd5", lit(asset(a, "archive", "hash", ""))),
        ("binaryUrl", lit(asset(a, "binary", "url", ""))), ("binaryMd5", lit(asset(a, "binary", "hash", ""))),
        ("metaUrl", lit(asset(a, "meta", "url", ""))),
        ("iconSize", "%dull" % asset(a, "icon", "size", 0)),
        ("archiveSize", "%dull" % asset(a, "archive", "size", 0)),
        ("binarySize", "%dull" % asset(a, "binary", "size", 0)),
        ("uncompressedSize", "%dull" % a["uncompressed_size"]),
        ("downloads", "%du" % a["downloads"]), ("releaseDate", "%dll" % a["release_date"]),
        ("packageType", PACKAGE.get(a.get("package_type"), "PackageType::Unknown")),
        ("peripherals", strs(a["peripherals"])), ("platforms", strs(a["supported_platforms"])),
        ("flags", strs(a["flags"])), ("subdirectories", strs(a.get("subdirectories", []))),
    ]
    out.append("\t\t{" + ", ".join(".%s = %s" % kv for kv in fields) + "},")
out += ['\t};', '\tc.featuredSlug = %s;' % lit(max(picked, key=lambda a: a["release_date"])["slug"]),
        '\tc.finalize();', '}', '']
sys.stdout.write("\n".join(out))
